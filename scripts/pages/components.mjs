// Build-time components for every public document. No client rendering is required.
export const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

function attributes(values = {}) {
  return Object.entries(values).map(([name,value]) => ` ${name}="${escape(value)}"`).join('');
}

export function renderLink({href,label,attrs}) {
  return `<a href="${escape(href)}"${attributes(attrs)}>${escape(label)}</a>`;
}

export function renderHeader({home,locale,languages,languageLabel,assetBase}) {
  const current = languages?.find(language => language.locale === locale);
  return `<header class="site-header">
<a class="brand" href="${escape(home.href)}" aria-label="Fretboard Hero"${attributes(home.attrs)}>
<svg viewBox="0 0 900 550" width="152" height="93" aria-hidden="true" focusable="false"><image href="${assetBase}assets/home/product-wordmarks.webp" width="2700" height="550"/></svg>
</a>
${languages?`<details class="document-language-menu">
<summary aria-label="${escape(languageLabel)}">
<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><circle cx="12" cy="12" r="9"/><ellipse cx="12" cy="12" rx="4" ry="9"/><path d="M3 12h18M5 6.5h14M5 17.5h14"/></svg>
<span id="language-label">${escape(current.label)}</span>
<svg class="chevron" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true"><path d="m3 6 5 5 5-5"/></svg>
</summary>
<nav aria-label="${escape(languageLabel)}">
${languages.map(language => renderLink({...language,attrs:{lang:language.locale,hreflang:language.locale,'aria-current':String(language.locale===locale),...language.attrs}})).join('\n')}
</nav>
</details>`:''}
</header>`;
}

export function renderFooter({home,links = [],navigationLabel}) {
  return `<footer class="site-footer">
<a class="back-link" href="${escape(home.href)}"${attributes(home.attrs)}><span aria-hidden="true">←</span><span id="back-label">${escape(home.label)}</span></a>
<nav aria-label="${escape(navigationLabel)}">${links.map(renderLink).join('\n')}</nav>
</footer>`;
}

export function renderSection(section) {
  const table = section.table;
  return `<section class="content-section">
<h2>${escape(section.title)}</h2>
${(section.paragraphs || []).map(p => `<p>${escape(p)}</p>`).join('\n')}
${section.items ? `<ul>${section.items.map(p => `<li>${escape(p)}</li>`).join('')}</ul>` : ''}
${section.steps ? `<ol class="steps">${section.steps.map(p => `<li>${escape(p)}</li>`).join('')}</ol>` : ''}
${table ? `<div class="table-wrap"><table><caption>${escape(section.title)}</caption><thead><tr>${table.headers.map(v => `<th scope="col">${escape(v)}</th>`).join('')}</tr></thead><tbody>${table.rows.map(row => `<tr>${row.map((v,i) => i ? `<td>${escape(v)}</td>` : `<th scope="row">${escape(v)}</th>`).join('')}</tr>`).join('')}</tbody></table></div>` : ''}
</section>`;
}

export function renderFAQ(title,questions) {
  if (!questions.length) return '';
  return `<section class="content-section faq"><h2>${escape(title)}</h2>${questions.map(([q,a]) => `<details><summary>${escape(q)}</summary><p>${escape(a)}</p></details>`).join('\n')}</section>`;
}

export function renderRelated(title,pages) {
  return `<section class="related-pages"><h2>${escape(title)}</h2><div class="cards">${pages.map(page => `<a class="card" href="${escape(page.href)}"><h3>${escape(page.label)} <span aria-hidden="true">↗</span></h3><p>${escape(page.description)}</p></a>`).join('')}</div></section>`;
}

export function renderPage({locale,head,body,header,footer,navigation = '',skipLabel,mainId = 'main-content',layout = 'wide',assetBase = '/',scripts = [],styles = [],footerHTML}) {
  return `<!doctype html>
<!-- Generated by scripts/build-seo.mjs. See docs/SEO.md for content sources. -->
<html lang="${locale}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="theme-color" content="#030b17">
${head}
<link rel="stylesheet" href="${assetBase}theme.css?v=10.52.0">
<link rel="stylesheet" href="${assetBase}locales.css?v=10.52.0">
<link rel="stylesheet" href="${assetBase}public-pages.css?v=10.52.0">
${styles.map(src => `<link rel="stylesheet" href="${escape(src)}">`).join('\n')}
${scripts.map(src => `<script src="${escape(src)}" defer></script>`).join('\n')}
</head>
<body class="public-page">
<div class="app-stage" aria-hidden="true"></div>
<div class="public-shell">
<a class="skip-link" href="#${mainId}">${escape(skipLabel)}</a>
${renderHeader({...header,locale,assetBase})}
${navigation}
<main id="${mainId}" class="page-content page-content--${layout}" tabindex="-1">
${body}</main>
${footerHTML??renderFooter(footer)}
</div>
</body>
</html>
`;
}
